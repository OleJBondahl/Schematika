@dataclasses.dataclass(frozen=True)
class Node:
    """One class in the graph, with its structural metrics."""

    id: str
    name: str
    package: str
    module: str
    kind: str
    frozen: bool
    doc: str
    fields: tuple[tuple[str, str], ...]
    fan_in: int = 0
    fan_out: int = 0
    dependents: int = 0
    dependencies: int = 0
    pagerank: float = 0.0
    kcore: int = 0


@dataclasses.dataclass(frozen=True)
class Edge:
    """`src` uses `dst`; `parts` are sorted (kind, name-of-field-or-function) pairs."""

    src: str
    dst: str
    parts: tuple[tuple[str, str], ...]

    @property
    def kinds(self) -> tuple[str, ...]:
        """Distinct relation kinds, sorted."""
        return tuple(sorted({kind for kind, _ in self.parts}))

    def names(self, kinds: Set[str] | None = None) -> tuple[str, ...]:
        """Field/method/function names behind this edge, optionally for some kinds."""
        return tuple(
            sorted({n for k, n in self.parts if n and (kinds is None or k in kinds)})
        )


@dataclasses.dataclass(frozen=True)
class Graph:
    """Nodes, edges and adjacency, plus hub attributes with no resolvable type."""

    nodes: dict[str, Node]
    edges: tuple[Edge, ...]
    untyped: dict[str, tuple[str, ...]]
    out: dict[str, tuple[Edge, ...]]
    inc: dict[str, tuple[Edge, ...]]


@dataclasses.dataclass(frozen=True)
class Index:
    """Discovered classes and a simple-name lookup used to resolve annotations."""

    classes: dict[str, type]
    by_simple: dict[str, list[str]]

    def resolve(self, names: set[str], own: str, module: str) -> set[str]:
        """Map annotation identifiers to node ids, preferring module scope."""
        mod = importlib.import_module(module)
        found: set[str] = set()
        for name in names:
            obj = getattr(mod, name, None)
            if isinstance(obj, type) and _qn(obj) in self.classes:
                found.add(_qn(obj))
                continue
            cands = self.by_simple.get(name, [])
            if len(cands) == 1:
                found.add(cands[0])
            elif cands:
                same = [c for c in cands if _package(c) == _package(own)]
                if len(same) == 1:
                    found.add(same[0])
        found.discard(own)
        return found


def _qn(cls: type) -> str:
    return f"{cls.__module__}.{cls.__qualname__}".removeprefix("schematika.")


def _package(node_id: str) -> str:
    return node_id.split(".")[0]


def _kind(cls: type) -> str | None:
    checks = (
        ("dataclass", dataclasses.is_dataclass(cls)),
        ("enum", issubclass(cls, enum.Enum)),
        (None, issubclass(cls, BaseException)),
        ("protocol", getattr(cls, "_is_protocol", False)),
        ("namedtuple", issubclass(cls, tuple) and hasattr(cls, "_fields")),
        ("scalar", issubclass(cls, str | int | float)),
        ("hub", bool(HUB_NAME.search(cls.__name__))),
    )
    return next((name for name, hit in checks if hit), None)


def _annotation_names(ann: object) -> set[str]:
    out: set[str] = set()

    def walk(tp: object) -> None:
        if isinstance(tp, str):
            out.update(IDENT.findall(tp))
        elif isinstance(tp, typing.ForwardRef):
            out.update(IDENT.findall(tp.__forward_arg__))
        elif isinstance(tp, type):
            out.add(tp.__name__)
        else:
            for arg in typing.get_args(tp):
                walk(arg)

    walk(ann)
    return out


def _annotation_text(ann: object) -> str:
    if isinstance(ann, str):
        return ann
    if isinstance(ann, type):
        return ann.__name__
    return re.sub(r"\b[\w]+\.(?=[A-Za-z_])", "", repr(ann))


def discover() -> tuple[Index, list[tuple[str, FunctionType]]]:
    """Import every module (except `__main__`s) and collect classes and functions."""
    names = sorted(
        m.name for m in pkgutil.walk_packages(schematika.__path__, "schematika.")
    )
    classes: dict[str, type] = {}
    funcs: list[tuple[str, FunctionType]] = []
    for name in names:
        if name.endswith(".__main__"):  # mcp/__main__ starts a stdio server on import
            continue
        mod = importlib.import_module(name)
        for obj in vars(mod).values():
            if isinstance(obj, type) and obj.__module__ == name and _kind(obj):
                classes[_qn(obj)] = obj
            elif (
                inspect.isfunction(obj)
                and obj.__module__ == name
                and not obj.__name__.startswith("_")
            ):
                funcs.append((name, obj))
    by_simple: dict[str, list[str]] = defaultdict(list)
    for node_id, cls in classes.items():
        by_simple[cls.__name__].append(node_id)
    return Index(classes, dict(by_simple)), funcs


def _is_self_attr(target: ast.expr) -> bool:
    return (
        isinstance(target, ast.Attribute)
        and isinstance(target.value, ast.Name)
        and target.value.id == "self"
    )


def _hub_edges(
    index: Index, node_id: str, cls: type, add: Callable[[str, str, str, str], None]
) -> list[str]:
    """Record a hub's attribute and signature edges; return its untyped attributes."""
    untyped: list[str] = []
    module = cls.__module__
    tree = ast.parse(textwrap.dedent(inspect.getsource(cls)))
    class_level = {id(n) for n in ast.iter_child_nodes(tree.body[0])}
    for node in ast.walk(tree):
        if not isinstance(node, ast.AnnAssign):
            continue
        target = node.target
        if id(node) not in class_level and not _is_self_attr(target):
            continue  # an annotated local variable, not state
        via = target.attr if isinstance(target, ast.Attribute) else ast.unparse(target)
        text = ast.unparse(node.annotation)
        dsts = index.resolve(set(IDENT.findall(text)), node_id, module)
        for dst in dsts:
            add(node_id, dst, "holds", via)
        if not dsts and (
            "Any" in text or "tuple[str" in text or text.startswith("list")
        ):
            untyped.append(f"{via}: {text}")
    for name, fn in cls.__dict__.items():
        fn = fn.__func__ if isinstance(fn, staticmethod | classmethod) else fn
        if not inspect.isfunction(fn) or (name.startswith("_") and name != "__init__"):
            continue
        for arg, ann in fn.__annotations__.items():
            kind = "returns" if arg == "return" else "takes"
            for dst in index.resolve(_annotation_names(ann), node_id, module):
                add(node_id, dst, kind, name)
    return untyped


def _collect_edges(
    index: Index, funcs: list[tuple[str, FunctionType]]
) -> tuple[dict[tuple[str, str], set[tuple[str, str]]], dict[str, tuple[str, ...]]]:
    raw: dict[tuple[str, str], set[tuple[str, str]]] = defaultdict(set)

    def add(src: str, dst: str, kind: str, via: str) -> None:
        raw[(src, dst)].add((kind, via))

    untyped: dict[str, tuple[str, ...]] = {}
    for node_id, cls in index.classes.items():
        kind = _kind(cls)
        if kind == "dataclass":
            for f in dataclasses.fields(cls):
                for dst in index.resolve(
                    _annotation_names(f.type), node_id, cls.__module__
                ):
                    add(node_id, dst, "field", f.name)
        for base in cls.__bases__:
            if base is not object and _qn(base) in index.classes:
                add(node_id, _qn(base), "inherits", "")
        if kind == "hub":
            found = _hub_edges(index, node_id, cls, add)
            if found:
                untyped[node_id] = tuple(found)
    for module, fn in funcs:
        own = module.removeprefix("schematika.") + ".<fn>"
        anns = getattr(fn, "__annotations__", {})
        returns = index.resolve(_annotation_names(anns.get("return")), own, module)
        params: set[str] = set()
        for arg, ann in anns.items():
            if arg != "return":
                params |= index.resolve(_annotation_names(ann), own, module)
        for ret in returns:
            for param in params - {ret}:
                add(ret, param, "flow", fn.__name__)
    return raw, untyped


def _node_fields(cls: type) -> tuple[tuple[str, str], ...]:
    if dataclasses.is_dataclass(cls):
        return tuple(
            (f.name, _annotation_text(f.type)) for f in dataclasses.fields(cls)
        )
    if issubclass(cls, enum.Enum):
        return tuple((m.name, repr(m.value)) for m in cls)
    return ()


def pagerank(ids: list[str], out: dict[str, list[str]]) -> dict[str, float]:
    """PageRank where rank flows to the types a type uses, so foundations rank high."""
    n = len(ids)
    rank = dict.fromkeys(ids, 1 / n)
    for _ in range(PAGERANK_ITERATIONS):
        dangling = sum(rank[i] for i in ids if not out[i])
        base = (1 - PAGERANK_DAMPING) / n + PAGERANK_DAMPING * dangling / n
        new = dict.fromkeys(ids, base)
        for i in ids:
            for j in out[i]:
                new[j] += PAGERANK_DAMPING * rank[i] / len(out[i])
        delta = sum(abs(new[i] - rank[i]) for i in ids)
        rank = new
        if delta < n * PAGERANK_TOLERANCE:
            break
    return rank


def core_numbers(adj: dict[str, set[str]]) -> dict[str, int]:
    """k-core number of every node of an undirected graph (peel min-degree first)."""
    degree = {i: len(js) for i, js in adj.items()}
    remaining = set(adj)
    core: dict[str, int] = {}
    k = 0
    while remaining:
        i = min(remaining, key=lambda x: (degree[x], x))
        k = max(k, degree[i])
        core[i] = k
        remaining.remove(i)
        for j in adj[i] & remaining:
            degree[j] -= 1
    return core


def _reach(start: str, adj: dict[str, list[str]]) -> set[str]:
    seen: set[str] = set()
    queue = deque([start])
    while queue:
        for nxt in adj[queue.popleft()]:
            if nxt not in seen and nxt != start:
                seen.add(nxt)
                queue.append(nxt)
    return seen


def build_graph() -> Graph:
    """Introspect the package and compute the graph with centrality metrics."""
    index, funcs = discover()
    raw, untyped = _collect_edges(index, funcs)
    edges = tuple(
        Edge(src, dst, tuple(sorted(parts)))
        for (src, dst), parts in sorted(raw.items())
    )
    ids = sorted(index.classes)
    typed = [e for e in edges if TYPED_SURFACE & set(e.kinds)]
    out_ids = {i: [e.dst for e in typed if e.src == i] for i in ids}
    in_ids = {i: [e.src for e in typed if e.dst == i] for i in ids}
    undirected = {i: (set(out_ids[i]) | set(in_ids[i])) - {i} for i in ids}
    rank = pagerank(ids, out_ids)
    cores = core_numbers(undirected)
    nodes: dict[str, Node] = {}
    for i in ids:
        cls = index.classes[i]
        kind = _kind(cls) or ""
        frozen = kind == "dataclass" and vars(cls)["__dataclass_params__"].frozen
        nodes[i] = Node(
            id=i,
            name=cls.__name__,
            package=_package(i),
            module=i.rsplit(".", 1)[0],
            kind=kind,
            frozen=frozen,
            doc=(inspect.getdoc(cls) or "").split("\n")[0][:140],
            fields=_node_fields(cls),
            fan_in=len(in_ids[i]),
            fan_out=len(out_ids[i]),
            dependents=len(_reach(i, in_ids)),
            dependencies=len(_reach(i, out_ids)),
            pagerank=round(rank[i], 6),
            kcore=cores[i],
        )
    out = {i: tuple(e for e in edges if e.src == i) for i in ids}
    inc = {i: tuple(e for e in edges if e.dst == i) for i in ids}
    return Graph(nodes, edges, untyped, out, inc)


# --- rendering helpers ------------------------------------------------------------


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _code(text: str) -> str:
    return f"`{_cell(text)}`" if text else ""


def _table(header: tuple[str, ...], rows: Iterable[tuple[str, ...]]) -> list[str]:
    lines = [f"| {' | '.join(header)} |", f"|{'---|' * len(header)}"]
    lines.extend(f"| {' | '.join(row)} |" for row in rows)
    return lines


def _tint(hex_color: str) -> str:
    rgb = [int(hex_color[i : i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(c + (255 - c) * 0.82):02x}" for c in rgb)


def _mid(node_id: str) -> str:
    return "n_" + re.sub(r"\W", "_", node_id)


def _mermaid(
    nodes: Iterable[Node], edges: Iterable[Edge], *, direction: str, labels: bool
) -> list[str]:
    nodes = sorted(nodes, key=lambda n: n.id)
    dupes = {name for name, c in Counter(n.name for n in nodes).items() if c > 1}
    lines = ["```mermaid", f"flowchart {direction}"]
    for n in nodes:
        text = f"{n.name}<br/>{n.module}" if n.name in dupes else n.name
        shape = f'(["{text}"])' if n.kind == "hub" else f'["{text}"]'
        lines.append(f"    {_mid(n.id)}{shape}:::pkg_{n.package}")
    for e in edges:
        label = e.names(STRUCTURAL)[:1] if labels else ()
        arrow = f"-->|{label[0]}|" if label else "-->"
        if not STRUCTURAL & set(e.kinds):
            arrow = "-.->"
        lines.append(f"    {_mid(e.src)} {arrow} {_mid(e.dst)}")
    for pkg in sorted({n.package for n in nodes}):
        color = PKG_COLOR.get(pkg, FALLBACK_COLOR)
        lines.append(
            f"    classDef pkg_{pkg} fill:{_tint(color)},stroke:{color},color:#1d1f21"
        )
    lines.append("```")
    return lines


def _names(graph: Graph, ids: Iterable[str], limit: int = 12) -> str:
    names = sorted({graph.nodes[i].name for i in ids})
    extra = f", +{len(names) - limit} more" if len(names) > limit else ""
    return ", ".join(f"`{n}`" for n in names[:limit]) + extra


def _details(summary: str, body: list[str]) -> list[str]:
    return ["<details>", f"<summary>{summary}</summary>", "", *body, "", "</details>"]


def _package_edges(graph: Graph) -> Counter[tuple[str, str]]:
    counts: Counter[tuple[str, str]] = Counter()
    for e in graph.edges:
        src, dst = graph.nodes[e.src].package, graph.nodes[e.dst].package
        if src != dst:
            counts[(src, dst)] += 1
    return counts


def _packages(graph: Graph) -> dict[str, list[Node]]:
    grouped: dict[str, list[Node]] = defaultdict(list)
    for n in graph.nodes.values():
        grouped[n.package].append(n)
    return dict(sorted(grouped.items()))


