"""Generate docs/data-model/ from the live schematika type graph.

Nodes are dataclasses, enums, ID scalars, protocols and the builder/hub classes.
Edges are typed references: dataclass fields, hub attributes and signatures,
inheritance, and module-level functions whose return type is built from their
parameter types. Function bodies are not analysed.

The whole output directory is generated; do not add hand-written files to it.
Needs every optional extra installed (`uv sync --all-extras`) so all modules import.

Usage:
    uv run python scripts/type_graph.py           # rewrite docs/data-model/
    uv run python scripts/type_graph.py --check   # exit 1 if the docs are stale
"""

